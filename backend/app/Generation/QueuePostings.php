<?php

namespace App\Generation;

use App\Llm\LlmPurpose;
use App\Llm\ModelRegistry;
use App\MasterCv\LoadMasterCvVersion;
use App\MasterCv\MasterCvIsNotUsable;
use App\Models\MasterCvVersion;
use App\Models\Posting;
use App\Models\Revision;
use App\Postings\PostingStatus;
use App\Revisions\RevisionSource;
use App\Revisions\RevisionStatus;
use Illuminate\Database\ConnectionInterface;

/**
 * Turns wanted postings into postings with a revision waiting to be
 * generated.
 *
 * **It sweeps `wanted` and never `captured`.** Capturing a posting is free and
 * speculative, and generating a CV for one is neither, so the decision to
 * spend is the owner's and is made explicitly. A captured posting nobody has
 * asked for stays where it is for ever and costs nothing.
 *
 * This is a step of its own rather than part of capture because it needs a
 * master CV that parses and lints, and capture must succeed without one: a
 * posting found while the CV is mid-edit is still a posting worth having. So a
 * CV that cannot be used leaves every posting exactly where it was, and the
 * first run after it is fixed picks up everything that was waiting.
 */
class QueuePostings
{
    public function __construct(
        private readonly LoadMasterCvVersion $masterCv,
        private readonly ModelRegistry $models,
        private readonly GenerationEvents $events,
        private readonly ConnectionInterface $database,
    ) {}

    /**
     * @throws MasterCvIsNotUsable When postings are waiting and the master CV
     *                             cannot be used. Nothing is queued and
     *                             nothing is lost.
     */
    public function handle(): QueueOutcome
    {
        $waiting = $this->waiting();

        // Nothing waiting is not an occasion to read the CV, let alone to
        // complain about it. A CV that fails its lint matters once there is
        // work for it, and until then an idle run says nothing at all.
        if ($waiting === []) {
            return QueueOutcome::nothingWaiting();
        }

        // Once per run rather than once per posting: a run that queues five
        // postings reads and lints one file.
        try {
            $version = $this->masterCv->handle();
        } catch (MasterCvIsNotUsable $blocked) {
            $this->events->queueBlocked(count($waiting), $blocked->problems);

            throw $blocked;
        }

        $queued = 0;

        foreach ($waiting as $posting) {
            $queued += $this->queue($posting, $version) ? 1 : 0;
        }

        return QueueOutcome::queued($queued, $version);
    }

    /**
     * Postings at `wanted` that carry no revision, oldest first.
     *
     * Identifiers rather than models: a posting holds a whole page's HTML and
     * none of it is needed to queue one. A posting still at `captured` is not
     * here, nor is a discarded one, and neither is one some earlier run
     * already gave a revision.
     *
     * @return list<int>
     */
    private function waiting(): array
    {
        /** @var list<int> */
        return Posting::query()
            ->where('status', PostingStatus::Wanted)
            ->whereDoesntHave('revisions')
            ->oldest('id')
            ->pluck('id')
            ->all();
    }

    /**
     * @return bool Whether this run was the one that queued it.
     */
    private function queue(int $posting, MasterCvVersion $version): bool
    {
        return $this->database->transaction(function () use ($posting, $version): bool {
            // The claim is the lock, and it is an ordinary conditional update
            // rather than `SELECT ... FOR UPDATE`: SQLite ignores row locks,
            // and nothing here may depend on one database's dialect. A
            // concurrent run that claimed this posting first has already moved
            // it off `wanted`, so this update matches no row and that run's
            // revision stays the only one. The same statement is what stops a
            // posting discarded between the read and the claim being queued.
            $claimed = Posting::query()
                ->whereKey($posting)
                ->where('status', PostingStatus::Wanted)
                ->update(['status' => PostingStatus::Queued]);

            if ($claimed === 0) {
                return false;
            }

            $revision = Revision::create([
                'posting_id' => $posting,
                'master_cv_version_id' => $version->id,
                'source' => RevisionSource::Generated,
                // Neither column may be null, and neither is a fact yet: the
                // prompt version is written again when the request is built
                // and the model when the response is stored, because a
                // revision that waited in `pending` across either change was
                // generated by the new one. What stands here is what would
                // generate it now.
                'model' => $this->models->for(LlmPurpose::Generation),
                'prompt_version' => PromptVersion::CURRENT,
                'status' => RevisionStatus::Pending,
            ]);

            // A second write because a revision has no identity until the
            // posting is claimed, and claiming it first is what makes two
            // concurrent runs safe. The transaction makes the pair one step.
            Posting::query()
                ->whereKey($posting)
                ->update(['current_revision_id' => $revision->id]);

            $this->events->queued($revision);

            return true;
        });
    }
}
