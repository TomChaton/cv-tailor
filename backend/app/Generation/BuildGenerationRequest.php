<?php

namespace App\Generation;

use App\Batching\BatchRequestBuilder;
use App\Llm\BatchRequest;
use App\Llm\LlmPurpose;
use App\Llm\LlmRequest;
use App\Llm\SystemBlock;
use App\MasterCv\Lint\MasterCvLinter;
use App\MasterCv\MasterCvParser;
use App\Models\Revision;

/**
 * Turns a revision into the request that generates it.
 *
 * The blocks go out ordered most to least stable — static instructions, then
 * the master CV, then this job — so the cache breakpoint on the master CV has
 * a fixed prefix in front of it and the only thing that changes between two
 * requests is the part after the breakpoint.
 */
class BuildGenerationRequest implements BatchRequestBuilder
{
    public function __construct(
        private readonly MasterCvParser $parser,
        private readonly MasterCvLinter $linter,
        private readonly OutputSchema $schema,
        private readonly PromptInstructions $instructions,
        private readonly MasterCvPrompt $masterCv,
        private readonly JobBrief $brief,
        private readonly GenerationEvents $events,
        private readonly int $maxTokens,
    ) {}

    /**
     * The batch lifecycle's unit: one request, tagged with the revision whose
     * result it is. The custom ID is the revision's ID, because the provider
     * returns a batch's results in any order.
     */
    public function batchRequestFor(Revision $revision): BatchRequest
    {
        return new BatchRequest((string) $revision->id, $this->handle($revision));
    }

    public function handle(Revision $revision): LlmRequest
    {
        $version = $revision->masterCvVersion()->firstOrFail();

        // The parse is re-derived from the stored raw content rather than
        // hydrated out of `parsed_json`. A hydrator would be a second reading
        // of the master CV format, kept in step with the parser by hand; the
        // raw content is stored for exactly this.
        $cv = $this->parser->parse($version->raw_content);

        // Linted here as well as where the version was stored. This is the
        // last point before a request leaves, and a CV with duplicate or
        // missing IDs produces a selection nobody can resolve.
        $report = $this->linter->lint($cv);

        if (! $report->passes()) {
            $this->events->refused($revision, $report);

            throw GenerationIsRefused::masterCvFailedLint($revision, $report);
        }

        // The revision records the prompt it is actually built from. One that
        // waited in `pending` across a prompt change is generated by the new
        // prompt, so the new version is what it was generated with; writing it
        // anywhere earlier would record an intention rather than a fact.
        $revision->fill(['prompt_version' => PromptVersion::CURRENT])->save();

        $ids = SelectableIds::from($cv);
        $instructions = $this->instructions->text();
        $masterCv = $this->masterCv->text($cv);
        $brief = $this->brief->text($revision->posting()->firstOrFail(), $cv->presentation);

        $this->events->promptBuilt(
            revision: $revision,
            enumCount: $ids->count(),
            keySkillsCap: $cv->presentation->maxKeySkills,
            instructionsChars: mb_strlen($instructions),
            masterCvChars: mb_strlen($masterCv),
            briefChars: mb_strlen($brief),
        );

        return new LlmRequest(
            purpose: LlmPurpose::Generation,
            system: [
                SystemBlock::text($instructions),
                SystemBlock::cacheable($masterCv),
            ],
            prompt: $brief,
            maxTokens: $this->maxTokens,
            schema: $this->schema->for($ids),
        );
    }
}
